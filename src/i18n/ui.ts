/** Path of a page in a language. `path` is the English path, e.g. "/workshops/". */
export function href(path: string, lang: Lang): string {
  if (lang === 'en') return path;
  return path === '/' ? `/${lang}/` : `/${lang}${path}`;
}

/**
 * Read a text field in a language. Italian falls back to English when the Italian
 * field is empty, and says so, so the page can mark the text as English.
 */
export function pick<T extends Record<string, unknown>>(
  data: T,
  field: string,
  lang: Lang,
): { value: string | undefined; fallback: boolean } {
  const en = data[field] as string | undefined;
  if (lang === 'en') return { value: en, fallback: false };
  const own = data[`${field}_${lang}`] as string | undefined; // only Italian fields exist so far; other languages fall back to English
  if (own && own.trim()) return { value: own, fallback: false };
  return { value: en, fallback: Boolean(en && en.trim()) };
}
